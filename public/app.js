// Placement conversation: a small state machine over the shared question bank.
// One speech path: Sarvam Realtime STT (live.js). No fallbacks; failures are shown and logged.
import { QUESTIONS, ACKS, PHRASES, LEVELS, variantFor } from '/shared/assessment.js';
import { Voice } from '/audio.js';
import { LiveSTT } from '/live.js';
import { log, initLogPanel } from '/log.js';

const $ = (id) => document.getElementById(id);
const app = document.querySelector('.app');
initLogPanel($('logs'));
const ui = {
  state: (s) => { if (app.dataset.state !== s) log('state', `${app.dataset.state} → ${s}`); app.dataset.state = s; },
  bot: (t) => ($('botLine').textContent = t),
  you: (t) => ($('youLine').textContent = t ? `“${t}”` : ''),
  hint: (t) => ($('hint').textContent = t || ''),
  card: (text, kind) => {
    const c = $('card');
    c.hidden = !text; c.textContent = text || ''; c.className = `card ${kind || ''}`;
  },
  progress: (i) => ($('progress').textContent = i == null ? '' : `${i + 1} / ${QUESTIONS.length}`),
};

const voice = new Voice((lvl) => document.documentElement.style.setProperty('--lvl', lvl.toFixed(3)));
let live = null;
let chipAction = null; // set by chip taps, consumed by the turn loop

// ---------- speaking ----------
async function say(text, { lang = 'en-IN', pace = 1 } = {}) {
  ui.state('speaking'); ui.bot(text);
  log('tts', `Sakhi says (${lang}, pace ${pace})`, text);
  try {
    const t = performance.now();
    const res = await fetch('/api/tts', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ text, lang, pace }) });
    const r = await res.json();
    const ms = Math.round(performance.now() - t);
    if (!res.ok || !r.audio) throw new Error(r.error || `HTTP ${res.status}`);
    const tr = r.trace || {};
    log('tts', tr.cached ? `Voice from server cache (${ms} ms round trip)` : `Voice generated by ${tr.model} in ${tr.ms} ms (${ms} ms round trip)`, tr);
    await voice.play(r.audio);
  } catch (e) {
    // No backup voice: the question stays on screen, and the conversation carries on.
    log('error', `Voice failed: ${e.message}. The prompt is shown as text only.`);
    ui.hint('Voice unavailable: please read the question above.');
    await new Promise((ok) => setTimeout(ok, 1500));
  }
}

// ---------- listening ----------
async function listen(silenceMs) {
  ui.state('listening'); ui.hint('Listening…');
  if (!(await live.ensureConnected())) {
    log('error', 'Could not reconnect to Sarvam Realtime', live.reason);
    ui.hint('');
    return { reason: 'live_failed', transcript: '', speechSec: 0 };
  }
  const r = await live.listen({ silenceMs, onNudge: () => ui.hint(PHRASES.nudge), onPartial: (t) => ui.you(t) });
  ui.hint('');
  return r;
}

async function submitTurn(qIndex, level, rec, prior) {
  ui.state('thinking'); ui.hint('…');
  const qs = new URLSearchParams({ q: qIndex, level, speechSec: rec.speechSec.toFixed(2) });
  if (prior) qs.set('prior', prior);
  const body = { transcript: rec.transcript, languageCode: rec.language };
  log('turn', 'POST /api/turn', { q: qIndex + 1, level, speechSec: +rec.speechSec.toFixed(2), ...body, ...(prior ? { prior } : {}) });
  const t = performance.now();
  const res = await fetch(`/api/turn?${qs}`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(body) });
  if (!res.ok) {
    const err = (await res.json().catch(() => ({}))).error || res.statusText;
    log('error', `/api/turn failed: HTTP ${res.status}`, err);
    throw new Error(err);
  }
  const r = await res.json();
  for (const step of r.trace || []) logTraceStep(step);
  log('turn', `Server decided: ${r.action}${r.intent ? ` (${r.intent})` : ''} in ${r.serverMs} ms (${Math.round(performance.now() - t)} ms round trip)`);
  return r;
}

// Turn one server trace step into a readable log line.
const TRACE_CAT = { intent: 'llm', judge: 'llm', reply: 'llm', features: 'score', heuristic: 'score', scores: 'score', level: 'score' };
function logTraceStep(st) {
  const { step, at, ms, error, ...d } = st;
  const p = `server +${at} ms · `;
  if (error) return log('error', `${p}${step} failed after ${ms} ms: ${error}`);
  const cat = TRACE_CAT[step] || 'turn';
  const msg = {
    input: () => `${p}input: ${d.via}`,
    question: () => `${p}evaluating ${d.id} (level ${d.level} version)`,
    check: () => `${p}${d.result}: ${d.why}`,
    clarify: () => d.intent ? `${p}clarification request detected: ${d.intent} (${d.by})` : `${p}no clarification request: scoring as an answer`,
    intent: () => `${p}${d.model} classified the short reply in ${ms} ms`,
    features: () => `${p}speech features measured`,
    heuristic: () => `${p}feature-based scores (0–4)`,
    judge: () => `${p}${d.model} rubric scores in ${ms} ms`,
    reply: () => `${p}${d.model} wrote the reply in ${ms} ms`,
    scores: () => `${p}final answer scores (${d.blend})`,
    level: () => `${p}provisional level ${d.provisionalLevel}: picks the versions of Q2–Q4`,
  }[step]?.() || `${p}${step}`;
  log(cat, msg, Object.keys(d).length ? d : undefined);
}

// ---------- one question, with the clarification ladder ----------
async function askQuestion(qIndex, level) {
  const q = QUESTIONS[qIndex];
  const v = variantFor(q, level);
  ui.progress(qIndex); ui.you('');
  ui.card(q.kind === 'open' && qIndex === 0 ? null : v.screen, q.kind === 'read' ? 'read' : '');
  log('app', `Question ${qIndex + 1} of ${QUESTIONS.length}: ${q.id} (${q.variants.any ? 'same for every level' : `level ${level} version`})`, v.screen);

  let confusions = 0, unheard = 0, neededHindi = false, prior = '';
  let prompt = { text: v.say, lang: 'en-IN', pace: 1 };
  const skipped = () => ({ questionId: q.id, kind: q.kind, variantLevel: level, skipped: true, neededHindi, features: {}, scores: zeroScores() });

  for (;;) {
    chipAction = null;
    live.beginPrompt();
    await say(prompt.text, prompt);
    // A chip tapped while the bot was talking skips straight to handling it.
    const rec = chipAction ? { reason: 'manual' } : await listen(q.silenceMs);
    let intent = chipAction; chipAction = null;

    let r = null;
    if (intent) log('app', `Chip "${intent}" handled for ${q.id}`);
    if (!intent) {
      if (rec.reason === 'no_speech') {
        intent = confusions === 0 ? 'in_hindi' : 'dont_know'; // 12s silence
        log('app', confusions === 0 ? 'Silence: offering the Hindi version' : 'Silence again: moving on');
      } else if (rec.reason === 'live_failed') {
        r = { action: 'didnt_hear' }; // connection dropped mid-answer; it reopens before the next listen
      } else {
        try { r = await submitTurn(qIndex, level, rec, prior); }
        catch (e) { log('error', `Turn failed: ${e.message}. Treating it as "didn't hear"`); r = { action: 'didnt_hear' }; }
        ui.you(r.transcript);
        if (r.action === 'clarify') intent = r.intent;
      }
    }

    if (intent === 'skip' || intent === 'dont_know' || (intent && confusions >= 2)) {
      log('app', `Moving on from ${q.id} (${intent === 'skip' ? 'skipped' : intent === 'dont_know' ? "learner doesn't know" : 'third clarification'}): scored 0`);
      await say(PHRASES.moveOn);
      return skipped();
    }
    if (intent) {
      confusions++;
      if (intent === 'in_hindi' || confusions === 2) {
        log('app', `Clarification ${confusions}: simpler English, then the Hindi version (counts as needing Hindi)`);
        neededHindi = true;
        // Say the simple English then the Hindi as two clips, so each uses the right voice language.
        await say(v.simple || v.say, { pace: 0.85 });
        prompt = { text: v.hindi, lang: 'hi-IN', pace: 0.9 };
      } else {
        log('app', `Clarification ${confusions}: repeating the question more slowly (pace 0.8)`);
        prompt = { text: v.say, lang: 'en-IN', pace: 0.8 }; // repeat / slower
      }
      continue;
    }
    if (r.action === 'didnt_hear') {
      log('app', `Didn't hear an answer (${unheard + 1} of 3)`);
      if (++unheard > 2) { await say(PHRASES.moveOn); return skipped(); }
      prompt = { text: PHRASES.didntHear, lang: 'en-IN', pace: 0.95 };
      continue;
    }
    if (r.action === 'cut_off') {
      log('app', 'Answer looks cut off: asking the learner to go on, and joining the next part to it');
      prior = r.transcript;
      prompt = { text: PHRASES.cutOff, lang: 'en-IN', pace: 1 };
      continue;
    }
    // scored
    log('app', `${q.id} answered`, { transcript: r.transcript, llmNote: r.llmNote });
    return { questionId: q.id, kind: q.kind, variantLevel: level, skipped: false, neededHindi, ...r };
  }
}

const zeroScores = () => ({ comprehension: 0, vocabulary: 0, grammar: 0, fluency: 0, pronunciation: 0, coherence: 0 });

// ---------- whole placement ----------
async function run() {
  $('chips').hidden = false;
  const answers = [];
  let level = 2;

  for (let i = 0; i < QUESTIONS.length; i++) {
    let a = await askQuestion(i, level);

    if (QUESTIONS[i].id === 'q1_intro') {
      level = a.skipped ? 1 : a.provisionalLevel ?? 2;
      log('app', `Provisional level ${level}: Q2–Q4 will use level ${level} versions`);
      await say(a.ack || ACKS[0]);
    } else if (QUESTIONS[i].id === 'q3_read' && !a.skipped && a.features.readAccuracy >= 0.95 && level < 4) {
      // Ceiling probe: strong reader gets the next level's sentence.
      log('app', `Read-aloud accuracy ${(a.features.readAccuracy * 100).toFixed(0)}%: trying a level ${level + 1} sentence`);
      await say("Great reading! Here's a slightly harder one.");
      const harder = await askQuestion(i, level + 1);
      if (!harder.skipped && harder.features.readAccuracy >= 0.8) { a = harder; level += 1; log('app', `Harder sentence read well: level raised to ${level}`); }
      else log('app', `Harder sentence accuracy ${harder.skipped ? 'n/a' : (harder.features.readAccuracy * 100).toFixed(0) + '%'}: keeping level ${level}`);
    } else if (i < QUESTIONS.length - 1) {
      await say(ACKS[(i % (ACKS.length - 1)) + 1]);
    }
    answers.push(a);
  }

  $('chips').hidden = true;
  await say(PHRASES.done);
  ui.state('thinking');
  log('turn', 'POST /api/final', answers.map((a) => ({ q: a.questionId, level: a.variantLevel, skipped: a.skipped, neededHindi: a.neededHindi })));
  const result = await fetch('/api/final', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ answers }) }).then((r) => r.json());
  log('score', `Final placement: level ${result.level} (${LEVELS[result.level]?.name}), adjusted score ${result.overall}`, result);
  showResult(result, answers);
}

function showResult(result, answers) {
  const L = LEVELS[result.level];
  ui.state('idle'); ui.card(null); ui.you(''); ui.hint(''); ui.progress(null);
  ui.bot(`You're a ${L.name} speaker 🎉`);
  const bars = Object.entries(result.dims || {}).map(([k, v]) =>
    `<div class="bar"><span>${k}</span><i><b style="width:${(v / 4) * 100}%"></b></i><span>${v.toFixed(1)}</span></div>`).join('');
  const el = $('result');
  el.hidden = false;
  el.innerHTML = `<h2>Level ${result.level} · ${L.name}</h2><p class="lvl">${L.blurb}</p>${bars}
    <details><summary>How we decided</summary><ul>${(result.reasons || []).map((r) => `<li>${r}</li>`).join('') || '<li>Weighted score across all four answers.</li>'}</ul>
    <pre>${escapeHtml(JSON.stringify(answers.map((a) => ({ q: a.questionId, level: a.variantLevel, transcript: a.transcript, hindi: a.neededHindi })), null, 1))}</pre></details>`;
  say(`You're a ${L.name} speaker! ${L.blurb}`);
}
const escapeHtml = (s) => s.replace(/[&<>]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;' })[c]);

// ---------- wiring ----------
$('chips').addEventListener('click', (e) => {
  const act = e.target.closest('button')?.dataset.act;
  if (!act) return;
  log('app', `Tapped "${e.target.closest('button').textContent.trim()}"`);
  if (act === 'done') return voice.stopListening?.(false); // wait for the final transcript
  chipAction = act;
  voice.stopPlayback?.();
  voice.stopListening?.(true);
});

let started = false;
$('orb').addEventListener('click', async () => {
  if (started) return voice.stopListening?.(false); // tapping the orb while listening = done speaking
  started = true;
  try {
    log('app', 'Session started');
    const cfg = await fetch('/api/config').then((r) => r.json());
    log('app', 'Server config', cfg);
    if (!cfg.ready) throw Object.assign(new Error(cfg.reason || 'Server is not configured'), { userMessage: 'The server has no Sarvam API key. Add SARVAM_API_KEY to .env and restart it.' });

    const params = new URLSearchParams(location.search);
    if (!voice.ctx) await voice.init({ noiseSuppression: params.get('ns') !== '0', autoGainControl: params.get('agc') !== '0' });
    live = new LiveSTT(voice);
    // Send audio from where the learner started talking (+250 ms margin), within the 2 s buffer.
    voice.onBargeIn = (leadMs) => { live.bargeInPrerollMs = Math.min(2000, leadMs + 250); };
    if (!(await live.connect())) {
      throw Object.assign(new Error(`Sarvam Realtime unavailable: ${live.reason}`), { userMessage: "I couldn't connect to the speech service. Check your connection and tap the bubble to try again." });
    }
    log('live', 'Connected: speech-to-text is Sarvam Realtime (streams only while listening)');
    await run();
  } catch (e) {
    log('error', `Session stopped: ${e.message}`);
    ui.state('idle');
    ui.bot(e.name === 'NotAllowedError' ? 'I need microphone access to talk with you.' : e.userMessage || `Something went wrong: ${e.message}`);
    live?.close(); live = null;
    started = false;
  }
});

// Greeting bubble on load.
ui.bot('Hi! 👋 Tap the bubble and let’s talk.');
